"""Build a SQLite database from the raw CSVs and run the analytical SQL questions."""

from __future__ import annotations

import re
import sqlite3
from pathlib import Path

import pandas as pd

RAW = Path("data/raw")
SQL = Path("sql")


def load_raw(raw_dir: Path = RAW) -> tuple[pd.DataFrame, pd.DataFrame]:
    pol = pd.read_csv(raw_dir / "rama_2023_05.csv", parse_dates=["fecha"])
    met = pd.read_csv(raw_dir / "redmet_2023_05.csv", parse_dates=["fecha"])
    pol.columns = [c.lower() for c in pol.columns]
    met.columns = [c.lower() for c in met.columns]
    return pol, met


def build_db(db_path: str | Path, raw_dir: Path = RAW, sql_dir: Path = SQL) -> sqlite3.Connection:
    con = sqlite3.connect(db_path)
    con.executescript((sql_dir / "schema.sql").read_text())
    pol, met = load_raw(raw_dir)
    for df, table in ((pol, "pollutants"), (met, "meteo")):
        df = df.assign(fecha=df["fecha"].dt.strftime("%Y-%m-%d"))
        df.to_sql(table, con, if_exists="append", index=False)
    return con


def parse_questions(text: str) -> list[dict]:
    """Split questions.sql into {'name', 'question', 'sql'} blocks."""
    blocks = re.split(r"(?m)^-- name: ", text)[1:]
    out = []
    for b in blocks:
        name, rest = b.split("\n", 1)
        q = re.search(r"(?m)^-- q: (.+)$", rest)
        sql = "\n".join(line for line in rest.splitlines() if not line.startswith("--")).strip()
        out.append({"name": name.strip(), "question": q.group(1).strip() if q else "", "sql": sql})
    return out


def daily_frame(con: sqlite3.Connection) -> pd.DataFrame:
    return pd.read_sql("SELECT * FROM daily ORDER BY fecha", con, parse_dates=["fecha"]).set_index("fecha")


def main() -> None:
    out = Path("reports")
    out.mkdir(exist_ok=True)
    con = build_db(":memory:")
    lines = [
        "# SQL answers",
        "",
        "Generated by `python -m airq.db` from `sql/questions.sql` on a SQLite build of the data.",
        "",
    ]
    for q in parse_questions((SQL / "questions.sql").read_text()):
        df = pd.read_sql(q["sql"], con)
        lines += [f"## {q['question']}", "", "```sql", q["sql"], "```", "", df.to_markdown(index=False), ""]
        print(f"\n# {q['question']}\n{df.to_string(index=False)}")
    (out / "sql_answers.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
